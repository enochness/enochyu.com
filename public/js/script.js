function coverHeight(item, text) {
  if (item.dataset.fitLines === undefined) return text.offsetHeight;
  const lines = parseInt(item.dataset.fitLines, 10);
  const top = text.firstElementChild.getBoundingClientRect().top;
  const sub = text.querySelector('h4');
  const p = text.querySelector('p');
  if (lines === 0 || !p) return sub.getBoundingClientRect().bottom - top - 1;
  const lineHeight = parseFloat(getComputedStyle(p).lineHeight);
  return p.getBoundingClientRect().top + lineHeight * lines - top - 1;
}

function fitCovers() {
  const groups = new Map();
  document.querySelectorAll('.with-cover').forEach(item => {
    const card = item.closest('.resume-card');
    if (!groups.has(card)) groups.set(card, []);
    groups.get(card).push(item);
  });
  groups.forEach(items => {
    let width = Infinity;
    items.forEach(item => {
      const cover = item.querySelector('.resume-cover');
      const text = item.querySelector('.resume-item-text');
      const img = cover.querySelector('img');
      const ratio = img.getAttribute('width') / img.getAttribute('height');
      cover.style.marginTop = '';
      let w = cover.offsetWidth;
      for (let i = 0; i < 3; i++) {
        w = Math.min(coverHeight(item, text) * ratio, item.clientWidth * 0.35);
        cover.style.width = w + 'px';
      }
      width = Math.min(width, w);
    });
    items.forEach(item => {
      const cover = item.querySelector('.resume-cover');
      cover.style.width = width + 'px';
      if (item.dataset.fitLines !== undefined) {
        const text = item.querySelector('.resume-item-text');
        const gap = coverHeight(item, text) - cover.offsetHeight;
        if (gap > 0) cover.style.marginTop = gap / 2 + 'px';
      }
    });
  });
}
window.addEventListener('load', fitCovers);
window.addEventListener('resize', fitCovers);

